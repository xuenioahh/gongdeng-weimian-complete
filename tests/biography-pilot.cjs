const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const source=fs.readFileSync(require.resolve('../src/data/history-biographies.js'),'utf8');
const context={};vm.runInNewContext(source+'\nthis.historyBiography138=historyBiography138;',context);
const record=(...titles)=>titles.map(title=>({title}));
const early=context.historyBiography138('gu',{flags:{},chronicle:[]});
assert.match(early,/潜邸嫡福晋/);assert.doesNotMatch(early,/薨|小鞋/);
const prior=context.historyBiography138('fang',{flags:{},chronicle:record('拾遗阁开门')});
assert.match(prior,/杏仁酥/);assert.doesNotMatch(prior,/顺贵人|偏院|替班者/);
const routine=context.historyBiography138('fang',{flags:{fangDead:true,fangInvestigation:'threeDays'},chronicle:record('听雨轩有喜')});
