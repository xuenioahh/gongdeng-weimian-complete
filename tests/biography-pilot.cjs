assert.match(routine,/煎药房/);assert.doesNotMatch(routine,/假口谕/);
assert.match(falseOrder,/偏院/);assert.doesNotMatch(falseOrder,/替班者/);
const unknownRoute=context.historyBiography138('fang',{flags:{fangDead:true},chronicle:record('听雨轩有喜')});
assert.match(unknownRoute,/服药后身故/);assert.doesNotMatch(unknownRoute,/偏院|替班者|假口谕/);
const afu=context.historyBiography138('afu',{flags:{fangDead:true,v68AfuPersonal:true},chronicle:record('听雨轩有喜')});
assert.match(afu,/尚宫局/);assert.match(afu,/张氏掌事宫女/);
