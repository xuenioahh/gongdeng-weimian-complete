#!/usr/bin/env python3
"""Build the offline distribution with Python's standard library only.

app.js and styles.css are generated outputs. Explicit manifests preserve lexical
scope and CSS cascade order while their source files are edited by responsibility.
"""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def javascript():
    manifest = json.loads((ROOT / 'src/bundle.json').read_text())
    pieces = ['/* Generated by scripts/build.py. Edit src/, then rebuild. */\n']
    def source(file):
        return '\n/* Source: ' + file + ' */\n' + (ROOT / file).read_text() + '\n'
    for unit in manifest['units']:
        if isinstance(unit, str):
            pieces.append(source(unit))
        else:
            pieces.append(unit['prefix'])
            pieces.extend(source(file) for file in unit['files'])
            pieces.append(unit['suffix'])
    return ''.join(pieces)


def stylesheet():
    manifest = json.loads((ROOT / 'styles/bundle.json').read_text())
    sources = {}
    for entry in manifest:
        file = entry['file']
        if file not in sources:
            text = (ROOT / file).read_text()
            blocks = re.split(r'/\* @block ([\w-]+) \*/', text)
            sources[file] = {blocks[i]: blocks[i+1].strip() for i in range(1,len(blocks),2)}
    return '/* Generated by scripts/build.py. Edit styles/, then rebuild. */\n' + '\n'.join(
        '/* '+item['file']+' : '+item['block']+' */\n'+sources[item['file']][item['block']]
        for item in manifest
    ) + '\n'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true', help='fail if generated files are stale')
    args = parser.parse_args()
    outputs = {'app.js': javascript(), 'styles.css': stylesheet()}
    for name, text in outputs.items():
        if args.check:
            if (ROOT/name).read_text() != text:
                raise SystemExit(name+' is stale; run python3 scripts/build.py')
        else:
            (ROOT/name).write_text(text)
    print('Distribution matches source modules.' if args.check else 'Built app.js and styles.css.')


if __name__ == '__main__':
    main()
