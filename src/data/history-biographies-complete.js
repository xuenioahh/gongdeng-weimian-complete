// Historical rank changes come from the completed chapter's own snapshot, never
// from today's title. Broad chapter dates stay broad rather than inventing a day.
function historyRankFacts151(key,s){
 const order=['答应','常在','贵人','嫔','妃','贵妃','皇贵妃','皇后','皇太后'];
 const rank=r=>{for(let i=order.length-1;i>=0;i--)if(String(r||'').endsWith(order[i]))return i;return -1;};
 let previous=null;const parts=[];
 for(let ci=0;ci<(s.chronicle||[]).length;ci++){
  const entry=s.chronicle[ci],snap=s.chapterSnapshots?.[ci];
  if(!entry||!snap?.ranks||!Object.hasOwn(snap.ranks,key))continue;
  const current=String(snap.ranks[key]||'');
  if(current===previous)continue;
  if(rank(current)<0){previous=current;continue;}
  if(/^故|^废/.test(current)){previous=current;continue;}
  const previousRank=rank(previous),newRank=rank(current);
  const verb=previousRank<0?'授':newRank<previousRank?'降为':newRank>previousRank?'晋为':'改封';
  parts.push(`${entry.date||CHAPTERS[ci]?.date||''}，${verb}${current}。`);previous=current;
 }
 return parts.join('');
}
